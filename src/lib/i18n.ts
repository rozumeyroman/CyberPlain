// Мови сайту, шляхи між ними й усі тексти інтерфейсу. Назва, слоган і футер — у site.config.ts.
// Чисті функції без astro:content, щоб імпортувати де завгодно.
export type Lang = 'uk' | 'en';
export const langs: Lang[] = ['uk', 'en'];
export const defaultLang: Lang = 'uk';

// Українська — у корені (/mitre/T1595/), англійська — під /en/ (/en/mitre/T1595/).
export const langOf = (u: URL): Lang => (/^\/en(\/|$)/.test(u.pathname) ? 'en' : 'uk');
export const stripLang = (path: string) => (path === '/en' ? '/' : path.replace(/^\/en\//, '/'));
export const localePath = (lang: Lang, path: string) => (lang === 'en' ? `/en${path}` : path);
// Та сама сторінка іншою мовою.
export const switchPath = (path: string, to: Lang) => localePath(to, stripLang(path));
// Для getStaticPaths сторінок у src/pages/[...lang]/: uk — без префікса (lang: undefined), en — /en/.
export const routeLang = (l: Lang) => (l === defaultLang ? undefined : l);
// Функція, а не масив: Astro змінює params між викликами, спільний масив ламає наступні сторінки.
export const langParams = () => langs.map((l) => ({ params: { lang: routeLang(l) } }));

// Відмінок після числа. uk: три форми (1 рішення, 3 рішення, 11 рішень), en: one/other.
export const plural = (lang: Lang, n: number, forms: readonly string[]) => {
  if (lang === 'en') return `${n} ${n === 1 ? forms[0] : forms[1]}`;
  const d = n % 10, h = n % 100;
  return `${n} ${d === 1 && h !== 11 ? forms[0] : d >= 2 && d <= 4 && (h < 12 || h > 14) ? forms[1] : forms[2]}`;
};

// Лише слово з plural(), без числа: для підписів, де число стоїть окремо.
const word = (lang: Lang, n: number, forms: readonly string[]) => plural(lang, n, forms).replace(/^\d+ /, '');

