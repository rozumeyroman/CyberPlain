// Дата з ISO (рік, рік-місяць або повна) у мові сторінки.
export const fmtDate = (lang: Lang, iso: string) => {
  const [y, m, d] = iso.split('-').map(Number);
  const opts: Intl.DateTimeFormatOptions = { timeZone: 'UTC', year: 'numeric', ...(m ? { month: 'long' } : {}), ...(d ? { day: 'numeric' } : {}) };
  return new Intl.DateTimeFormat(lang === 'uk' ? 'uk-UA' : 'en-GB', opts).format(new Date(Date.UTC(y, (m ?? 1) - 1, d ?? 1)));
};

